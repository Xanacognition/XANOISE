"""XENOISE: the names WND-1's files (firmware/src/wb/) define that JIANT's also do, both being one compilation unit
each. Out: firmware/src/wb/wb_names.h, included by xn_wb.c around wb/: each clashing identifier renamed wb_ while
WND-1's code is compiled (WB_NAMES_ON), and back (WB_NAMES_OFF); each clashing macro pushed, undefined and popped.
Run after changing either side:  tools/wb_names.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "firmware" / "src"
KW = set("""auto break case char const continue default do double else enum extern float for goto if inline int long
register restrict return short signed sizeof static struct switch typedef union unsigned void volatile while uint8_t
uint16_t uint32_t int8_t int16_t int32_t int64_t uint64_t size_t NULL""".split())


def strip(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    s = re.sub(r"//[^\n]*", " ", s)
    s = re.sub(r"__attribute__\s*\(\((?:[^()]|\([^()]*\))*\)\)", " ", s)
    s = re.sub(r"\b(POOL|RAMFN|HOT|WASM_EXPORT\s*\([^)]*\))\b", " ", s)
    return re.sub(r'"(\\.|[^"\\])*"', '""', s)


def defined(text):
    """(identifiers, macros) a C file defines at its top level"""
    t = strip(text)
    macros = set(re.findall(r"^\s*#\s*define\s+([A-Za-z_]\w*)", t, re.M))
    ids = set()
    depth, i, top = 0, 0, []
    for ch in t:                                         # the text at brace depth 0, each body a ';'
        if ch == "{":
            depth += 1
            if depth == 1: top.append(";")
            continue
        if ch == "}":
            depth -= 1
            continue
        top.append(ch if depth == 0 else ("\n" if ch == "\n" else " "))
    top = "".join(top)
    for m in re.finditer(r"\benum\b[^{;]*\{([^}]*)\}", t):          # enum constants (anywhere)
        for item in m.group(1).split(","):
            n = re.match(r"\s*([A-Za-z_]\w*)", item)
            if n: ids.add(n.group(1))
    for m in re.finditer(r"\btypedef\b[^;]*?\b([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*;", t, re.S):
        ids.add(m.group(1))
    for m in re.finditer(r"\bstruct\s+([A-Za-z_]\w*)\s*\{", t):
        ids.add(m.group(1))
    for st in re.split(r"[;}]", top):                    # declarations at the top level
        st = re.sub(r"^\s*#[^\n]*", "", st, flags=re.M).strip()
        if not st or st.startswith(("typedef",)): continue
        fn = re.search(r"\b([A-Za-z_]\w*)\s*\([^()]*(?:\([^()]*\)[^()]*)*\)\s*$", st)
        if fn and not re.search(r"=", st.split("(")[0]):
            ids.add(fn.group(1)); continue
        head = st.split("=")[0]
        for part in head.split(","):
            n = re.findall(r"\b([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*$", part.strip())
            if n: ids.add(n[-1])
    return ids - KW, macros


def main():
    wb_ids, wb_mac = set(), set()
    for f in sorted((SRC / "wb").glob("*")):
        if f.name == "wb_names.h": continue
        i, m = defined(f.read_text())
        wb_ids |= i; wb_mac |= m
    j_ids, j_mac = set(), set()
    files = [f for f in SRC.glob("*.c") if f.name != "xn_wb.c"] + list(SRC.glob("*.h")) + \
            list((ROOT / "firmware" / "hal").glob("*.h")) + list((ROOT / "build" / "gen").glob("*.h")) + \
            [ROOT / "tests" / "hostsim.c", ROOT / "tests" / "ui_test.c", ROOT / "web" / "emu" / "felucca_web.c"]
    for f in files:
        i, m = defined(f.read_text(errors="replace"))
        j_ids |= i; j_mac |= m
    keep = {"RGB"}                                       # the same on both sides
    ren = sorted((wb_ids & (j_ids | j_mac)) - wb_mac)
    mac = sorted((wb_mac & (j_ids | j_mac)) - keep)
    L = ["/* generated by tools/wb_names.py: WND-1's names (wb/) that JIANT's sources define too. Not for editing */",
         "#if defined(WB_NAMES_ON)", "#undef WB_NAMES_ON"]
    L += [f'#pragma push_macro("{n}")\n#undef {n}' for n in mac + [n for n in ren if n in j_mac]]
    L += [f"#define {n} wb_{n}" for n in ren]
    L += ["#elif defined(WB_NAMES_OFF)", "#undef WB_NAMES_OFF"]
    L += [f"#undef {n}" for n in ren]
    L += [f'#undef {n}\n#pragma pop_macro("{n}")' for n in mac]
    L += [f'#pragma pop_macro("{n}")' for n in ren if n in j_mac]
    L += ["#endif"]
    (SRC / "wb" / "wb_names.h").write_text("\n".join(L) + "\n")
    print(f"wb_names: {len(ren)} names renamed, {len(mac)} macros set aside: {', '.join(ren[:30])} .. | {', '.join(mac)}")


if __name__ == "__main__":
    main()
