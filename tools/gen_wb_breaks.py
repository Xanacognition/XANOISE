"""XENOISE: WND-1's six breaks as hits for JIANT's DRUM engine (no samples: they would not fit beside JIANT). The lanes
are WND-1's (tools/gen_breaks.py BREAKS there: 16 steps an instrument, '.' or a velocity 1-9, an articulation letter,
':' a roll, ';' a drag, '^' a flam). A cell of the BRK track names a slice (a 16th of the bar); playing it plays that
step's hits on the DRUM lanes (firmware/src/wb/wb_seq.c brk_slice).
Out: firmware/src/wb/wb_brk.h: BRK_NAME, BRK_SWING (the odd 16ths' lateness, 1/256 of a step), BRK_HIT[6][16][4]
(lane | velocity 1..15 << 3 | 1 roll 2 drag 3 flam << 7; 0 none), BRK_TAG (1 kick, 2 snare, 4 hats, 8 the rest).
  gen_wb_breaks.py OUT.h"""
import sys

BREAKS = [
    ("SOLEIL", 0.06, {"K": "9 . . . . . . . 7 . 9 . . . . 4", "S": ". . 2 . 9k . 3 . . . 3 2 9k . . 5",
                      "R": "7b . 5 . 6 . 5 4 7b . 5 . 6 . 5 4", "Y": "8 . . . . . . . . . . . . . . .",
                      "H": ". . . . 4p . . . . . . . 4p . . ."}),
    ("GRELOT", 0.0, {"K": "9 . . 7 . . 8 . . 6 . . . . 8 .", "S": ". . . . 9 . . 2 . 3 . . 9 . . 2",
                     "H": "4 2 8 2 4 2 8 2 4 2 8 2 4 2 8o 2", "T": "6 . 3 . 6h . 3 . 6 . 3 . 6h . 3 ."}),
    ("TENDU", 0.03, {"K": "9 . 4 . . . 7 . 8 . . 7 . . . .", "S": ". 2 . 3 9 . 2 3 . 3 . . 9 2 . 3",
                     "P": ". . . . 7 . . . . . . . 7 . . .", "H": "7 . 4 . 7 . 4 3 7 . 4 . 7 . 5h ."}),
    ("ABYSSE", 0.08, {"K": "9 . . . . . . 5 . . 9 . . . . .", "X": "9 . . . . . . . . . 8 . . . . .",
                      "S": ". . . . 9k . . 3 . 2 . . 9k . 8: 8:", "H": ". . 6 . . . 6 . . . 6 . . . 6 .",
                      "Z": "3 2 5 2 3 2 5 2 3 2 5 2 3 2 5 3", "J": ". . . 5k . . . . . . . 5k . . . ."}),
    ("MAMBO", 0.12, {"K": "9 . . 5 . . 7 . 8 . . . . . 6 .", "S": ". . . . 8 . . . . . 3 . 8 . . 4",
                     "H": ". . 3 . . . 3 . . . 3 . . . 3 .", "W": "8 . 4d . 7 . 4d . 8 . 4d . 7 . 4d .",
                     "C": "3b . 3t . 7s . 7 6 3b . 3t . 7s . . .", "U": ". . . . . . . . . . . . . . 8 7",
                     "B": ". 4 . 6 . 4 . 7h . 4 . 6 . 4 . 7h"}),
    ("GRENIER", 0.30, {"K": "9 . . . . . . 6 8 . . 5 . . . .", "S": ". . . . 9 . . . . 3 . . 9 . . 2",
                       "H": "7 . 5 4 7 . 5 4 7 . 5 4 7 . 6h 4", "J": ". . . . . . 3 . . . . . . . 4 ."}),
]
KICK, SNARE, CLAP, CH, OH, TOM, RIM, CB = range(8)     # JIANT's DRUM lanes (DRUM_LANE_NOTE 36 38 39 42 46 45 37 56)
TAG = {KICK: 1, SNARE: 2, CLAP: 2, CH: 4, OH: 4}


def lane_of(inst, art):
    if inst in "KX": return KICK
    if inst == "S": return RIM if art == "k" else SNARE
    if inst == "P": return CLAP
    if inst == "H": return OH if art in "oh" and art else CH
    if inst == "R": return CB if art == "b" else OH       # the ride: its bell on the cowbell, its body an open hat
    if inst == "Y": return OH
    if inst in "TZ": return OH if art == "h" else CH       # tambourine, shaker: a hat
    if inst in "CUBM": return TOM
    if inst == "W": return CB
    if inst == "J": return RIM
    raise SystemExit(inst)


def main(out):
    L = ["/* generated by tools/gen_wb_breaks.py: WND-1's breaks as DRUM hits (no samples), GPL-3.0-only */",
         "#pragma once", "#include <stdint.h>", f"#define BRK_N {len(BREAKS)}u",
         "static const char *const BRK_NAME[BRK_N] = {" + ", ".join(f'"{b[0]}"' for b in BREAKS) + "};",
         "static const uint8_t BRK_SWING[BRK_N] = {" + ", ".join(str(round(b[1] * 256)) for b in BREAKS) + "};"]
    hits, tags = [], []
    for name, _, lanes in BREAKS:
        rows, trow = [], []
        for step in range(16):
            got = {}
            for inst, lane in lanes.items():
                tok = lane.split()[step]
                if tok == ".": continue
                vel, art, mod = int(tok[0]), tok[1:2] if tok[1:2].isalpha() else "", tok[-1] if tok[-1] in ":;^" else ""
                ln = lane_of(inst, art)
                v = min(15, round(vel * 15 / 9))
                m = {":": 1, ";": 2, "^": 3}.get(mod, 0)
                if v > got.get(ln, (0, 0))[0]: got[ln] = (v, m)
            cell = sorted(got.items(), key=lambda x: -x[1][0])[:4]
            assert len(got) <= 4, (name, step, got)
            words = [ln | v << 3 | m << 7 for ln, (v, m) in cell] + [0] * (4 - len(cell))
            rows.append("{" + ", ".join(map(str, words)) + "}")
            trow.append(str(sum(TAG.get(ln, 8) for ln, (v, _) in cell if v >= 7)))
        hits.append("    {" + ", ".join(rows) + "}")
        tags.append("{" + ", ".join(trow) + "}")
    L.append("static const uint16_t BRK_HIT[BRK_N][16][4] = {\n" + ",\n".join(hits) + "};")
    L.append("static const uint8_t BRK_TAG[BRK_N][16] = {" + ", ".join(tags) + "};")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
