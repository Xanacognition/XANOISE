"""(XENOISE) The tracker's screen font, smooth: firmware/src/wb/wb_font.h from IBM Plex Mono (SIL OFL 1.1).

  tools/gen_wb_font.py OUT.h [--fonts DIR]

The cells and baselines of WND-1's CLAIRE, so every page draws where it did (kawa_gfx.c g_text, g_text_l):
  S   8 px a character in a 12 x 16 box (2 px of pad), capitals from row 3 to row 10 (CLAIRE's 2..11, a size smaller:
      air in the cell, as Z-NOISE's), the baseline row 11: Medium
  SB  the same in SemiBold: T_BOLD (it was the strokes drawn twice, a pixel apart)
  L   16 px a character in a 24 x 32 box (4 px of pad), capitals and digits from row 2 to row 19: Medium
Each glyph is drawn 8 times larger, outline unhinted, and filtered down: edges at a fraction of a pixel (4-bit
alpha), the capitals' height exact, the characters narrowed to their cell (Plex Mono is 0.6 em wide).
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SS = 8                                          # supersampling
CAP = 0.698                                     # Plex Mono's capital height, em


def face(path, adv, box_w, box_h, pad, cap_top, cap_px, first, last, gamma):
    size = cap_px / CAP * SS
    font = ImageFont.truetype(str(path), size=round(size))
    xs = adv / (0.6 * cap_px / CAP)             # the narrowing to the cell
    base = (cap_top + cap_px) * SS
    data, off, bw = [], [], []
    for code in range(first, last + 1):
        ch = chr(code)
        wide = round(box_w * SS / xs)
        img = Image.new("L", (wide, box_h * SS), 0)
        ImageDraw.Draw(img).text((round(pad * SS / xs), base), ch, fill=255, font=font, anchor="ls")
        img = img.resize((box_w, box_h), Image.Resampling.BOX)
        px = list(img.tobytes())
        off.append(len(data))
        bw.append(box_w)
        for r in range(box_h):
            row = [min(15, round(((px[r * box_w + c] / 255) ** gamma) * 15)) for c in range(box_w)]
            for c in range(0, box_w, 2):
                data.append(row[c] << 4 | (row[c + 1] if c + 1 < box_w else 0))
    return data, off, bw


def c_array(kind, name, vals, per=24):
    lines = [f"static const {kind} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(f"0x{v:02x}" if kind == "uint8_t" and "DATA" in name else str(v)
                                         for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out")
    ap.add_argument("--fonts", default=str(ROOT / "assets" / "fonts"))
    a = ap.parse_args()
    fd = Path(a.fonts)
    faces = [("FONT_S_CLAIRE", "IBMPlexMono-Medium.ttf", 8, 12, 16, 2, 3, 8, 32, 126, 0.8),
             ("FONT_SB_CLAIRE", "IBMPlexMono-SemiBold.ttf", 8, 12, 16, 2, 3, 8, 32, 126, 0.8),
             ("FONT_L_CLAIRE", "IBMPlexMono-Medium.ttf", 16, 24, 32, 4, 2, 18, 32, 95, 0.85)]
    out = ["/* generated by tools/gen_wb_font.py from IBM Plex Mono (SIL OFL 1.1: LICENSES/OFL-IBMPlexMono.txt). Do not edit.",
           " * (XENOISE) the tracker's screen font: CLAIRE's cells and baselines (S 8 x 16, L 16 x 32), drawn smooth: Medium,",
           " * SemiBold for T_BOLD, SemiBold large */", "#pragma once"]
    for name, ttf, adv, bw_, h, pad, top, cap, first, last, g in faces:
        data, off, bw = face(fd / ttf, adv, bw_, h, pad, top, cap, first, last, g)
        n = last - first + 1
        out.append(f"/* {name}: {ttf} */")
        out.append(c_array("uint8_t", f"{name}_DATA", data))
        out.append(c_array("uint16_t", f"{name}_OFF", off))
        out.append(c_array("uint8_t", f"{name}_ADV", [adv] * n))
        out.append(c_array("uint8_t", f"{name}_BW", bw))
        out.append(f"static const felucca_font_t {name} = {{ {h}, {pad}, {first}, {last}, {name}_ADV, {name}_BW, "
                   f"{name}_OFF, {name}_DATA }};")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"{a.out}: {', '.join(f[0] for f in faces)}")


if __name__ == "__main__":
    main()
